"""UI translations. The selected language is applied once, before building windows.

Russian source strings are the fallback. Format parameters are inserted *after*
translation, so profile names, URLs and other user data never become catalog keys.
"""
from PySide6.QtCore import QCoreApplication, QLibraryInfo, QTranslator

from outward_app.core.models import normalize_language
from outward_app.paths import asset_path


_language = "ru"


def set_language(language: str) -> None:
    global _language
    _language = normalize_language(language)
    app = QCoreApplication.instance()
    if app is None:
        return
    translator = getattr(app, '_outward_qt_translator', None)
    if translator is not None:
        app.removeTranslator(translator)
    if _language == 'en':
        return
    if translator is None:
        translator = QTranslator(app)
        # The frozen app bundles this catalog; source runs use PySide6's copy.
        if not translator.load(str(asset_path('translations/qtbase_ru.qm'))):
            translator.load('qtbase_ru', QLibraryInfo.path(QLibraryInfo.LibraryPath.TranslationsPath))
        # Keep the Python wrapper alive for the QApplication's lifetime.
        app._outward_qt_translator = translator
    app.installTranslator(translator)


def tr(source: str, *args) -> str:
    text = ENGLISH.get(source, source) if _language == "en" else source
    return text.format(*args) if args else text


def traffic_text(value: int | None) -> str:
    from outward_app.core.traffic import format_traffic

    formatted = format_traffic(value)
    if _language == 'ru' or value is None:
        return formatted
    amount, unit = formatted.rsplit(' ', 1)
    return amount.replace(',', '.') + ' ' + tr(unit)


